import type {
  PICase,
  PIMessage,
  PISettings,
  PISpec,
  PIOutboxRecord,
} from "@luma/shared";

export class PolicyError extends Error {}
export function requirePolicy(
  condition: unknown,
  reason: string,
): asserts condition {
  if (!condition) throw new PolicyError(reason);
}
export function sanitizeBody(input: string): string {
  return input
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .split(
      /\n\s*(?:On .{0,200}wrote:|From:|Begin forwarded message:|[-_]{2,}\s*(?:Original Message|Forwarded message)|--\s*$)/im,
    )[0]
    .split("\n")
    .filter((line) => !/^\s*>/.test(line))
    .join("\n")
    .replace(
      /\b(?:MRN|patient(?:\s+name)?|DOB|DOS|date of (?:birth|service)|member\s*id|SSN)\s*[:=#-]\s*[^\n,;]+/gi,
      "[REDACTED]",
    )
    .replace(/\b\d{3}-\d{2}-\d{4}\b/g, "[REDACTED]")
    .replace(
      /\b(?:Bearer\s+\S+|(?:api[_ -]?key|password|refresh[_ -]?token|access[_ -]?token)\s*[:=]\s*\S+)/gi,
      "[REDACTED]",
    )
    .trim()
    .slice(0, 12000);
}
export function redactTree<T>(value: T): T {
  if (typeof value === "string") return sanitizeBody(value) as T;
  if (Array.isArray(value)) return value.map(redactTree) as T;
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, redactTree(v)]),
    ) as T;
  return value;
}
export function allowedInbound(
  m: PIMessage,
  s: PISettings,
  authorizedThread = false,
): boolean {
  const from = m.from.toLowerCase();
  if (
    from === s.mailbox.toLowerCase() ||
    s.ignoredSenders.includes(from) ||
    m.autoGenerated ||
    m.labels.some((l) => ["SENT", "SPAM", "TRASH", "DRAFT"].includes(l))
  )
    return false;
  if (
    /^(?:mailer-daemon|postmaster|no-?reply)@/i.test(from) ||
    /^(?:automatic reply|out of office|undeliverable|delivery status)/i.test(
      m.subject,
    )
  )
    return false;
  const domain = from.split("@")[1];
  return (
    authorizedThread ||
    s.allowedSenders.map((x) => x.toLowerCase()).includes(from) ||
    s.allowedDomains.includes(domain) ||
    s.contacts.some((c) => c.active && c.canClarify && c.address === from)
  );
}
export function requirePrivacy(s: PISettings) {
  requirePolicy(
    s.privacyReviewed &&
      s.providerAgreementsConfirmed &&
      s.dataPolicyReference.trim(),
    "Live processing requires a reviewed data policy and confirmed provider agreements",
  );
}
export function requireProcessingAuthorization(s: PISettings) {
  if (s.modelInputMode === "automatic") {
    requirePolicy(
      process.env.PI_AUTOMATIC_EMAIL_ANALYSIS === "true" &&
        Boolean(process.env.PI_AUTOMATIC_EMAIL_AUTHORIZATION?.trim()) &&
        process.env.PI_REASONER_PROVIDER === "local_cli" &&
        process.env.PI_CLARIFICATION_SEND_LOCK === "true" &&
        s.mode === "draft_only" &&
        Boolean(
          process.env.PI_GMAIL_REQUIRED_THREAD_SENDERS ||
          process.env.PI_GMAIL_REQUIRED_THREAD_SENDER,
        ),
      "Automatic email analysis requires explicit deployment authorization, the isolated local runner, a sender restriction and the send lock",
    );
    return;
  }
  if (s.modelInputMode !== "reviewed_summary") requirePrivacy(s);
}
export function highRisk(spec: PISpec, settings: PISettings): boolean {
  const content =
    `${spec.workflow} ${spec.title} ${spec.inScope.join(" ")} ${spec.expectedBehavior} ${spec.dataMigrationImpact}`.toLowerCase();
  return (
    ["high", "critical"].includes(spec.riskLevel) ||
    spec.type === "data_correction" ||
    settings.highRiskWorkflows.some(
      (w) => content.includes(w.replaceAll("_", " ")) || content.includes(w),
    ) ||
    /\b(?:phi|clinical|patient|billing|authorization|insurance|linkage|access control|migration|bulk (?:edit|update)|ehr)\b/i.test(
      content,
    )
  );
}
export function recipientsFor(
  contactIds: string[],
  workflow: string,
  settings: PISettings,
  approval = false,
): string[] {
  requirePolicy(contactIds.length > 0, "No configured recipients");
  return [
    ...new Set(
      contactIds.map((contactId) => {
        const c = settings.contacts.find((c) => c.id === contactId);
        requirePolicy(
          c?.active && c.canClarify && (!approval || c.canApproveScope),
          "Recipient is inactive or lacks required role",
        );
        requirePolicy(
          c.workflows.includes(workflow),
          "Recipient is not authorized for this workflow",
        );
        requirePolicy(
          settings.sandboxRecipients.includes(c.address),
          "Recipient must be in sandbox allowlist",
        );
        return c.address;
      }),
    ),
  ];
}
export function checkSend(
  c: PICase,
  row: PIOutboxRecord,
  s: PISettings,
  locked: boolean,
  previous: PIOutboxRecord[],
  now: Date,
) {
  requirePolicy(
    !locked,
    "Outbound email is locked by the deployment administrator",
  );
  requirePolicy(!c.demo, "Demo messages cannot use live Gmail");
  requirePolicy(
    !s.receiveOnly,
    "Inbox receive-only mode prohibits email sending",
  );
  requirePolicy(
    s.mode === "autonomous" && !s.paused && !s.killSwitch && !s.sendDryRun,
    "Autonomous sends are disabled",
  );
  requirePrivacy(s);
  requirePolicy(
    !["SUSPENDED", "CLOSED", "ESCALATED", "REJECTED", "DUPLICATE"].includes(
      c.state,
    ),
    "Case is not eligible for sending",
  );
  for (const recipient of row.recipients)
    requirePolicy(
      s.sandboxRecipients.includes(recipient) &&
        s.contacts.some(
          (x) =>
            x.address === recipient &&
            x.active &&
            x.canClarify &&
            x.workflows.includes(c.workflow) &&
            (row.kind !== "approval" || x.canApproveScope),
        ),
      "Recipient policy changed",
    );
  requirePolicy(
    row.specVersion === c.specVersion,
    "Outbox references an old specification",
  );
  const sent = previous.filter(
    (x) =>
      ["sent", "sending", "uncertain"].includes(x.state) && x.id !== row.id,
  );
  requirePolicy(
    sent.filter(
      (x) => x.updatedAt.slice(0, 10) === now.toISOString().slice(0, 10),
    ).length < s.dailyOutboundLimit,
    "Daily outbound limit reached",
  );
  const caseSent = sent.filter((x) => x.caseId === c.id);
  requirePolicy(
    caseSent.filter((x) => x.kind === "clarification").length <
      s.maxFollowUps || row.kind !== "clarification",
    "Follow-up limit reached",
  );
  requirePolicy(
    !caseSent.some(
      (x) =>
        now.getTime() - Date.parse(x.updatedAt) < s.cooldownMinutes * 60000,
    ),
    "Outbound cooldown active",
  );
  const hour = Number(
    new Intl.DateTimeFormat("en-GB", {
      timeZone: s.timezone,
      hour: "2-digit",
      hourCycle: "h23",
    }).format(now),
  );
  requirePolicy(
    hour >= s.businessHours.start && hour < s.businessHours.end,
    "Outside configured business hours",
  );
  requirePolicy(
    !/\[REDACTED\]|\b(?:MRN|SSN|DOB)\s*:/i.test(row.bodyText),
    "Sensitive content requires human review",
  );
}
