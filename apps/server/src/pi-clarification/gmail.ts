export interface GmailClient {
  profile(): Promise<{ emailAddress: string; historyId: string }>;
  listMessages(
    query: string,
    labels: string[],
    pageToken?: string,
  ): Promise<{
    messages?: { id: string; threadId: string }[];
    nextPageToken?: string;
  }>;
  getMessage(id: string): Promise<PIMessage>;
  getThread(id: string): Promise<PIMessage[]>;
  getThreadMetadata(id: string): Promise<PIMessage[]>;
  history(
    cursor: string,
    pageToken?: string,
  ): Promise<{
    historyId: string;
    history?: {
      messagesAdded?: { message: { id: string; threadId: string } }[];
    }[];
    nextPageToken?: string;
  }>;
  watch(
    topic: string,
    labels: string[],
  ): Promise<{ historyId: string; expiration: string }>;
  sendReply(row: PIOutboxRecord, source: PIMessage): Promise<string>;
  findSent(rfcMessageId: string): Promise<string | null>;
  createDraft(row: PIOutboxRecord, source: PIMessage): Promise<string>;
  attachment(messageId: string, attachmentId: string): Promise<Buffer>;
}
export class GmailError extends Error {
  constructor(
    readonly status: number,
    readonly retryAfterSeconds = 0,
  ) {
    super(`Gmail request failed (${status})`);
  }
}
type Part = {
  mimeType?: string;
  filename?: string;
  headers?: { name: string; value: string }[];
  body?: { data?: string; size?: number; attachmentId?: string };
  parts?: Part[];
};
type RawMessage = {
  id: string;
  threadId: string;
  internalDate?: string;
  labelIds?: string[];
  payload?: Part;
};
function header(part: Part, name: string) {
  return (
    part.headers?.find((x) => x.name.toLowerCase() === name.toLowerCase())
      ?.value || ""
  );
}
function address(value: string): string {
  const angle = [...value.matchAll(/<\s*([^<>]+?)\s*>/g)];
  if (angle.length > 1) return "invalid@invalid.invalid";
  const candidate =
    angle.length === 1
      ? angle[0][1]
      : value.replace(/"(?:[^"\\]|\\.)*"/g, "").trim();
  const match = candidate
    .trim()
    .match(/(?:^|\s)([a-zA-Z0-9.!#$%&'*+\/=?^_`{|}~-]+@[a-zA-Z0-9.-]+)$/);
  return match?.[1]?.toLowerCase() || "invalid@invalid.invalid";
}
function addresses(value: string) {
  return value.split(",").filter(Boolean).map(address).slice(0, 50);
}
function bodyOf(p: Part): string {
  if (p.filename) return "";
  if (p.parts) {
    const plain = p.parts
      .filter((x) => x.mimeType === "text/plain")
      .map(bodyOf)
      .filter(Boolean);
    return (plain.length ? plain : p.parts.map(bodyOf)).join("\n");
  }
  if (
    !["text/plain", "text/html"].includes(p.mimeType || "") ||
    !p.body?.data ||
    (p.body.size || 0) > 100000
  )
    return "";
  return Buffer.from(p.body.data, "base64url").toString("utf8").slice(0, 30000);
}
function attachmentMetadata(
  part: Part,
): { id: string; mimeType: string; size: number; label: string }[] {
  const all: { id: string; mimeType: string; size: number; label: string }[] =
    [];
  const visit = (p: Part) => {
    if (p.body?.attachmentId)
      all.push({
        id: p.body.attachmentId,
        mimeType: p.mimeType || "application/octet-stream",
        size: p.body.size || 0,
        label: `Attachment ${all.length + 1}`,
      });
    for (const child of p.parts || []) visit(child);
  };
  visit(part);
  return all.slice(0, 30);
}
export function normalizeMessage(raw: RawMessage, mailbox: string): PIMessage {
  const p = raw.payload || {},
    from = address(header(p, "From")),
    auth = header(p, "Authentication-Results");
  const authDomain = auth
    .match(/dmarc=pass[^;]*header\.from=([^;\s]+)/i)?.[1]
    ?.toLowerCase();
  const identityVerified =
    /^\s*mx\.google\.com\s*;/i.test(auth) && authDomain === from.split("@")[1];
  return PIMessageSchema.parse({
    id: raw.id,
    threadId: raw.threadId,
    mailbox,
    from,
    to: addresses(header(p, "To")),
    cc: addresses(header(p, "Cc")),
    subject: sanitizeBody(header(p, "Subject")).slice(0, 500),
    body: sanitizeBody(bodyOf(p)),
    rfcMessageId:
      header(p, "Message-ID") || `<gmail-${raw.id}@unknown.invalid>`,
    inReplyTo: header(p, "In-Reply-To").slice(0, 500),
    references: header(p, "References").slice(0, 2000),
    date: new Date(Number(raw.internalDate) || Date.now()).toISOString(),
    labels: raw.labelIds || [],
    attachments: attachmentMetadata(p),
    direction:
      from === mailbox.toLowerCase() || raw.labelIds?.includes("SENT")
        ? "outgoing"
        : "incoming",
    autoGenerated:
      !["", "no"].includes(header(p, "Auto-Submitted").toLowerCase()) ||
      /(?:bulk|junk)/i.test(header(p, "Precedence")) ||
      Boolean(header(p, "X-Autoreply")),
    identityVerified,
    demo: false,
  });
}
const safeHeader = (s: string) => {
  requirePolicy(!/[\r\n\x00]/.test(s), "Invalid email header");
  return s;
};
export function replyMime(
  row: PIOutboxRecord,
  source: PIMessage,
  mailbox: string,
) {
  const subject = /^Re:/i.test(source.subject)
    ? source.subject
    : `Re: ${source.subject}`;
  const encodedSubject = `=?UTF-8?B?${Buffer.from(safeHeader(subject)).toString("base64")}?=`;
  const references = `${source.references} ${source.rfcMessageId}`
    .trim()
    .slice(-1800);
  const raw = [
    `From: PI AI Support Assistant <${safeHeader(mailbox)}>`,
    `To: ${row.recipients.map(safeHeader).join(", ")}`,
    `Subject: ${encodedSubject}`,
    `Message-ID: ${safeHeader(row.rfcMessageId)}`,
    `In-Reply-To: ${safeHeader(source.rfcMessageId)}`,
    `References: ${safeHeader(references)}`,
    "MIME-Version: 1.0",
    'Content-Type: text/plain; charset="UTF-8"',
    "Content-Transfer-Encoding: base64",
    "",
    Buffer.from(row.bodyText)
      .toString("base64")
      .match(/.{1,76}/g)
      ?.join("\r\n") || "",
  ].join("\r\n");
  return {
    threadId: source.threadId,
    raw: Buffer.from(raw).toString("base64url"),
  };
}
export class GmailAdapter implements GmailClient {
  private token: { value: string; expiresAt: number } | null = null;
  constructor(
    readonly vault: CredentialVault,
    readonly mailbox: string,
    readonly locked = true,
    readonly fetcher: typeof fetch = fetch,
    readonly tokenProvider?: GmailTokenProvider,
    readonly requiredSender: string | null = process.env
      .PI_GMAIL_REQUIRED_THREAD_SENDER || null,
  ) {}
  private async accessToken() {
    if (this.token && this.token.expiresAt > Date.now() + 60000)
      return this.token.value;
    if (this.tokenProvider) {
      this.token = await this.tokenProvider.accessToken();
      return this.token.value;
    }
    const response = await this.fetcher("https://oauth2.googleapis.com/token", {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        client_id: process.env.PI_GMAIL_CLIENT_ID || "",
        client_secret: process.env.PI_GMAIL_CLIENT_SECRET || "",
        refresh_token: this.vault.get(this.mailbox),
        grant_type: "refresh_token",
      }),
      signal: AbortSignal.timeout(15000),
    });
    if (!response.ok) throw new GmailError(response.status);
    const result = (await response.json()) as {
      access_token: string;
      expires_in: number;
    };
    requirePolicy(
      result.access_token,
      "Gmail token refresh returned no access token",
    );
    this.token = {
      value: result.access_token,
      expiresAt: Date.now() + result.expires_in * 1000,
    };
    return result.access_token;
  }
  private async call<T>(
    route: string,
    method = "GET",
    body?: unknown,
  ): Promise<T> {
    // The host is fixed; model output cannot supply URLs or credentials.
    const response = await this.fetcher(
      `https://gmail.googleapis.com/gmail/v1/users/me/${route}`,
      {
        method,
        headers: {
          Authorization: `Bearer ${await this.accessToken()}`,
          "Content-Type": "application/json",
        },
        body: body ? JSON.stringify(body) : undefined,
        signal: AbortSignal.timeout(20000),
      },
    );
    if (!response.ok) {
      if (response.status === 401) this.token = null;
      throw new GmailError(
        response.status,
        Number(response.headers.get("retry-after") || 0),
      );
    }
    return response.json() as Promise<T>;
  }
  profile() {
    return this.call<{ emailAddress: string; historyId: string }>("profile");
  }
  listMessages(query: string, labels: string[], pageToken?: string) {
    const params = new URLSearchParams({ q: query, maxResults: "100" });
    for (const label of labels) params.append("labelIds", label);
    if (pageToken) params.set("pageToken", pageToken);
    return this.call<{
      messages?: { id: string; threadId: string }[];
      nextPageToken?: string;
    }>(`messages?${params}`);
  }
  async getThreadMetadata(threadId: string) {
    const params = new URLSearchParams({ format: "metadata" });
    for (const name of [
      "From",
      "To",
      "Cc",
      "Subject",
      "Message-ID",
      "In-Reply-To",
      "References",
      "Authentication-Results",
      "Auto-Submitted",
      "Precedence",
      "List-Id",
      "X-Autoreply",
    ])
      params.append("metadataHeaders", name);
    const result = await this.call<{ messages?: RawMessage[] }>(
      `threads/${encodeURIComponent(threadId)}?${params}`,
    );
    return (result.messages || []).map((m) =>
      normalizeMessage(m, this.mailbox),
    );
  }
  private async requireEligibleThread(threadId: string) {
    if (this.requiredSender)
      requirePolicy(
        qualifyingAnchor(
          await this.getThreadMetadata(threadId),
          this.requiredSender,
          this.mailbox,
          threadId,
        ),
        "Thread excluded: no message from the required sender",
      );
  }
  async getMessage(messageId: string) {
    if (this.requiredSender) {
      const meta = await this.call<RawMessage>(
        `messages/${encodeURIComponent(messageId)}?format=metadata&metadataHeaders=From`,
      );
      await this.requireEligibleThread(meta.threadId);
    }
    return normalizeMessage(
      await this.call<RawMessage>(
        `messages/${encodeURIComponent(messageId)}?format=full`,
      ),
      this.mailbox,
    );
  }
  async getThread(threadId: string) {
    await this.requireEligibleThread(threadId);
    const result = await this.call<{ messages?: RawMessage[] }>(
      `threads/${encodeURIComponent(threadId)}?format=full`,
    );
    return (result.messages || [])
      .map((x) => normalizeMessage(x, this.mailbox))
      .sort((a, b) => a.date.localeCompare(b.date));
  }
  history(cursor: string, pageToken?: string) {
    const params = new URLSearchParams({
      startHistoryId: cursor,
      historyTypes: "messageAdded",
      maxResults: "100",
    });
    if (pageToken) params.set("pageToken", pageToken);
    return this.call<{
      historyId: string;
      history?: {
        messagesAdded?: { message: { id: string; threadId: string } }[];
      }[];
      nextPageToken?: string;
    }>(`history?${params}`);
  }
  watch(topic: string, labels: string[]) {
    return this.call<{ historyId: string; expiration: string }>(
      "watch",
      "POST",
      { topicName: topic, labelIds: labels, labelFilterBehavior: "include" },
    );
  }
  async sendReply(row: PIOutboxRecord, source: PIMessage) {
    requirePolicy(
      !this.locked && !this.tokenProvider?.readOnly,
      "Outbound Gmail transport locked",
    );
    requirePolicy(!source.demo, "Demo cannot send email");
    await this.requireEligibleThread(source.threadId);
    const result = await this.call<{ id: string }>(
      "messages/send",
      "POST",
      replyMime(row, source, this.mailbox),
    );
    return result.id;
  }
  async createDraft(row: PIOutboxRecord, source: PIMessage) {
    requirePolicy(
      !this.locked &&
        !this.tokenProvider?.readOnly &&
        process.env.PI_GMAIL_ALLOW_DRAFT_WRITES === "true",
      "Gmail draft writes disabled",
    );
    await this.requireEligibleThread(source.threadId);
    const result = await this.call<{ id: string }>("drafts", "POST", {
      message: replyMime(row, source, this.mailbox),
    });
    return result.id;
  }
  async findSent(rfcId: string) {
    const result = await this.listMessages(
      `in:sent rfc822msgid:${rfcId.replace(/[<>]/g, "")}`,
      [],
    );
    for (const m of result.messages || []) {
      if (
        !this.requiredSender ||
        qualifyingAnchor(
          await this.getThreadMetadata(m.threadId),
          this.requiredSender,
          this.mailbox,
          m.threadId,
        )
      )
        return m.id;
    }
    return null;
  }
  async attachment(messageId: string, attachmentId: string) {
    if (this.requiredSender) {
      const meta = await this.call<RawMessage>(
        `messages/${encodeURIComponent(messageId)}?format=metadata&metadataHeaders=From`,
      );
      await this.requireEligibleThread(meta.threadId);
    }
    const raw = await this.call<RawMessage>(
      `messages/${encodeURIComponent(messageId)}?format=full`,
    );
    const find = (p: Part): Part | undefined =>
      p.body?.attachmentId === attachmentId
        ? p
        : p.parts?.map(find).find(Boolean);
    const part = raw.payload ? find(raw.payload) : undefined;
    requirePolicy(
      part &&
        (part.body?.size || Infinity) <= 256000 &&
        ["text/plain", "text/csv"].includes(part.mimeType || ""),
      "Only plain text/CSV attachments under 256 KB may be read",
    );
    const result = await this.call<{ data: string; size: number }>(
      `messages/${encodeURIComponent(messageId)}/attachments/${encodeURIComponent(attachmentId)}`,
    );
    requirePolicy(result.size <= 256000, "Attachment exceeds limit");
    const bytes = Buffer.from(result.data, "base64url");
    requirePolicy(bytes.length <= 256000, "Attachment exceeds limit");
    return Buffer.from(sanitizeBody(bytes.toString("utf8")), "utf8");
  }
}
export class FakeGmail implements GmailClient {
  messages: PIMessage[] = [];
  sent: PIOutboxRecord[] = [];
  failAfterSend = false;
  calls = 0;
  expired = false;
  watches = 0;
  async profile() {
    return { emailAddress: "pi@demo.invalid", historyId: "100" };
  }
  async listMessages() {
    return {
      messages: this.messages.map((m) => ({ id: m.id, threadId: m.threadId })),
    };
  }
  async getMessage(messageId: string) {
    const m = this.messages.find((m) => m.id === messageId);
    if (!m) throw new GmailError(404);
    return m;
  }
  async getThread(threadId: string) {
    return this.messages.filter((m) => m.threadId === threadId);
  }
  async getThreadMetadata(threadId: string) {
    return this.messages
      .filter((m) => m.threadId === threadId)
      .map((m) => ({ ...m, body: "", attachments: [] }));
  }
  async history() {
    if (this.expired) throw new GmailError(404);
    return {
      historyId: "101",
      history: [
        {
          messagesAdded: this.messages.map((m) => ({
            message: { id: m.id, threadId: m.threadId },
          })),
        },
      ],
    };
  }
  async watch() {
    this.watches++;
    return { historyId: "101", expiration: String(Date.now() + 604800000) };
  }
  async sendReply(row: PIOutboxRecord) {
    this.calls++;
    this.sent.push(row);
    if (this.failAfterSend) throw new Error("Network timeout");
    return `fake-${row.id}`;
  }
  async findSent(rfc: string) {
    return this.sent.find((x) => x.rfcMessageId === rfc)?.id || null;
  }
  async createDraft() {
    return "fake-draft";
  }
  async attachment() {
    return Buffer.from("de-identified demo evidence");
  }
}
