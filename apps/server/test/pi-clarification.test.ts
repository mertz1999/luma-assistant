function message(s: PIService, changes: Partial<PIMessage> = {}): PIMessage {
  return {
    id: `msg-${Math.random()}`,
    threadId: "thread-1",
    mailbox: s.store.settings().mailbox,
    from: s.demo ? "client@demo.invalid" : "client@example.test",
    to: [s.store.settings().mailbox],
    cc: [],
    subject: "Generic display question",
    body: "A generic configured label is absent",
    rfcMessageId: `<${Math.random()}@example.test>`,
    inReplyTo: "",
    references: "",
    date: s.store.at(),
    labels: ["INBOX"],
    attachments: [],
    autoGenerated: false,
    identityVerified: true,
    demo: s.demo,
    ...changes,
  };
}
function triaged(s: PIService) {
  const m = message(s),
    caseId = s.orchestrator.ingest(m, s.demo)!;
  s.workflow.transition(caseId, "TRIAGING", "test", "Triage");
  return { caseId, m };
}
function requested(s: PIService) {
  const { caseId, m } = triaged(s),
    r = s.workflow.propose(caseId, spec(), "test");
  const out = s.approvals.request(caseId, ["demo-client"]);
  s.outbox.simulate(out.id);
  return { caseId, m, r, out };
}
function validReply(
  s: PIService,
  r: ReturnType<typeof requested>,
  changes: Partial<PIMessage> = {},
) {
  const reply = message(s, {
    body: `APPROVE ${r.caseId} v${r.r.version}`,
    inReplyTo: r.out.rfcMessageId,
    references: r.out.rfcMessageId,
    ...changes,
  });
  s.orchestrator.ingest(reply, s.demo);
  return reply;
}

